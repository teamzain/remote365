const translateFallbackWords = (text: string, lang: Language): string => {
    if (lang === 'en' || /@|https?:|remote365:|remotelink:|\/api|^\d/.test(text)) return text;
    const words = wordFallbackTranslations[lang as Exclude<Language, 'en'>];
    if (!words) return text;
    let translated = text;
    Object.keys(words)
        .sort((a, b) => b.length - a.length)
        .forEach((word) => {
            translated = translated.replace(new RegExp(`\\b${word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'gi'), (match) => {
                const replacement = words[word];
                return match === match.toUpperCase() ? replacement.toUpperCase() : replacement;
            });
        });
    return translated;
};

export const translateStaticText = (value: string, lang?: string): string => {
    const l = (lang && supportedLanguages.includes(lang as Language) ? lang : 'en') as Language;
    const leading = value.match(/^\s*/)?.[0] || '';
    const trailing = value.match(/\s*$/)?.[0] || '';
    const text = value.trim();
    if (!text) return value;
    if (l === 'en') return value;
    const supplemental = supplementalTranslations[text]?.[l];
    if (supplemental) return `${leading}${supplemental}${trailing}`;
    const key = staticTextToKey.get(text);
    if (key) return `${leading}${translateKey(key, l)}${trailing}`;
    const translated = translateFallbackWords(translateFallbackPhrases(text, l), l);
    return `${leading}${translated}${trailing}`;
};

export const applyGlobalTranslations = (root: ParentNode = document.body, lang?: string): void => {
    if (typeof document === 'undefined') return;
    const isKnownTranslation = (original: string, current: string) => {
        return supportedLanguages.some((language) => translateStaticText(original, language) === current);
    };

    const translateTextNode = (node: Text) => {
        const parent = node.parentElement;
        if (!parent || ['SCRIPT', 'STYLE', 'TEXTAREA', 'CODE', 'PRE'].includes(parent.tagName)) return;
        const current = node.nodeValue || '';
        let original = originalTextNodes.get(node) || current;
        if (originalTextNodes.has(node) && current !== original && !isKnownTranslation(original, current)) {
            original = current;
        }
        originalTextNodes.set(node, original);
        const translated = translateStaticText(original, lang);
        if (node.nodeValue !== translated) node.nodeValue = translated;
    };

    const translateElement = (element: Element) => {
        translatableAttributes.forEach((attribute) => {
            if (!element.hasAttribute(attribute)) return;
            const stored = originalAttributes.get(element) || {};
            const current = element.getAttribute(attribute) || '';
            let original = stored[attribute] || current;
            if (stored[attribute] && current !== original && !isKnownTranslation(original, current)) {
                original = current;
            }
            stored[attribute] = original;
            originalAttributes.set(element, stored);
            const translated = translateStaticText(original, lang);
            if (element.getAttribute(attribute) !== translated) {
                element.setAttribute(attribute, translated);
            }
        });
    };

    if (root instanceof Element) translateElement(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    let current = walker.nextNode();
    while (current) {
        if (current.nodeType === Node.TEXT_NODE) translateTextNode(current as Text);
        if (current.nodeType === Node.ELEMENT_NODE) translateElement(current as Element);
        current = walker.nextNode();
    }
};

export const t = (key: string, lang?: string): string => {
    const k = key as keyof typeof translations;
    const l = (lang && supportedLanguages.includes(lang as Language) ? lang : 'en') as Language;
    if (supplementalTranslations[key]) return supplementalTranslations[key][l] || supplementalTranslations[key].en || key;
    if (l === 'ar-SA' && Object.prototype.hasOwnProperty.call(arabicSaudiTranslations, key)) return arabicSaudiTranslations[key];
    if (translations[k]) {
        const entry = translations[k] as Partial<Record<Language, string>> & { en: string };
        return entry[l] || entry.en;
    }
    return key;
};
